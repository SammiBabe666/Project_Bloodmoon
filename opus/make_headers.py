"""Writes the two generated headers of the Opus 2 port of BLOODMOON (run it after changing the SVG):

    python opus/make_headers.py

  bm_sine.h : the 8192-step sine table (Q15) the voices and the screen use (defined in bloodmoon.c, declared in bm.h). op1r's build read the firmware's own
              table at a fixed address; Opus plugins carry their own, so this one is the same formula,
              round(32767 * sin(2 pi k / 8192)).
  bm_art.h  : bloodmoon.svg as a C string. At start the plugin writes it into its folder on the OP-1
              (opus_art_text) and hands that file to the engine service as its T1 screen.
Standard library only."""
import math
import os

HERE = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'noladrift.bloodmoon')

vals = [round(32767 * math.sin(2 * math.pi * k / 8192)) for k in range(8192)]
with open(os.path.join(HERE, 'bm_sine.h'), 'w', newline='\n') as f:
    f.write('/* Generated by opus/make_headers.py: do not edit. sin(2 pi k / 8192) in Q15. */\n')
    f.write('const short BM_SINE[8192] = {\n')
    for i in range(0, 8192, 16):
        f.write('    ' + ', '.join(str(v) for v in vals[i:i + 16]) + ',\n')
    f.write('};\n')

svg = open(os.path.join(HERE, 'bloodmoon.svg'), 'rb').read()
assert len(svg) <= 65536, 'the core loads art up to 64 KB'
with open(os.path.join(HERE, 'bm_art.h'), 'w', newline='\n') as f:
    f.write('/* Generated by opus/make_headers.py from bloodmoon.svg: do not edit. */\n')
    f.write('static const char BM_SVG[] =\n')
    for line in svg.decode('ascii').splitlines(keepends=True):
        esc = (line.replace('\\', '\\\\').replace('"', '\\"').replace('\t', '\\t')
               .replace('\r', '\\r').replace('\n', '\\n'))
        f.write(f'    "{esc}"\n')
    f.write(';\n')
print('wrote bm_sine.h and bm_art.h,', len(svg), 'bytes of SVG')

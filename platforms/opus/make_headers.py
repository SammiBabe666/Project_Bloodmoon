"""Writes the two generated headers of the Opus 2 port of BLOODMOON (run it after changing the SVG):

    python platforms/opus/make_headers.py

  bm_sine.h : a quarter of the 8192-step sine table (Q15), entries 0..2048, round(32767 * sin(2 pi k / 8192)): the
              same values as v1.3's full table (op1r's build read the firmware's own table at a fixed address),
              folded by symmetry in bm.h's bm_sin. 4 KB, so it fits the OP-1's fast memory (opl_init copies it there).
  bm_art.h  : the OP-1 screen's bloodmoon.svg (platforms/op1/src/plugins/bloodmoon/, the one copy of the art) as a
              C string. At start the plugin writes it into its folder on the OP-1
              (opus_art_text) and hands that file to the engine service as its T1 screen.
Standard library only."""
import math
import os

PLATFORM = os.path.dirname(os.path.abspath(__file__))
HERE = os.path.join(PLATFORM, 'src', 'noladrift.bloodmoon')
SVG = os.path.join(PLATFORM, '..', 'op1', 'src', 'plugins', 'bloodmoon', 'bloodmoon.svg')

vals = [round(32767 * math.sin(2 * math.pi * k / 8192)) for k in range(2049)]
with open(os.path.join(HERE, 'bm_sine.h'), 'w', newline='\n') as f:
    f.write('/* Generated by platforms/opus/make_headers.py: do not edit. sin(2 pi k / 8192) in Q15, k 0..2048 (a quarter turn). */\n')
    f.write('const short BM_QSINE[BM_QSINE_LEN] = {\n')
    for i in range(0, 2049, 16):
        f.write('    ' + ', '.join(str(v) for v in vals[i:i + 16]) + ',\n')
    f.write('};\n')

svg = open(SVG, 'rb').read()
assert len(svg) <= 65536, 'the core loads art up to 64 KB'
with open(os.path.join(HERE, 'bm_art.h'), 'w', newline='\n') as f:
    f.write('/* Generated by platforms/opus/make_headers.py from platforms/op1/src/plugins/bloodmoon/bloodmoon.svg: do not edit. */\n')
    f.write('static const char BM_SVG[] =\n')
    for line in svg.decode('ascii').splitlines(keepends=True):
        esc = (line.replace('\\', '\\\\').replace('"', '\\"').replace('\t', '\\t')
               .replace('\r', '\\r').replace('\n', '\\n'))
        f.write(f'    "{esc}"\n')
    f.write(';\n')
print('wrote bm_sine.h and bm_art.h,', len(svg), 'bytes of SVG')
